#!/usr/bin/env node
/**
 * scripts/make-seed.mjs
 * @why Generates `supabase/migrations/*_seed_calendar_2026_12.sql` from the
 *  approved editorial plan (`/home/isa/EG-Posts/calendario-2026-12.json`).
 *
 *  - pillars → `calendar_topics` (English labels + attention ranking)
 *  - posts   → `calendar_posts` (English titles, topic FK, real calendar dates)
 *
 * Run: node scripts/make-seed.mjs
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const ROOT = resolve(__dirname, '..')
const SOURCE = process.env.SEED_SOURCE || '/home/isa/EG-Posts/calendario-2026-12.json'

const YEAR = 2026
const MONTH = 12

/** topic key → [label, emoji, color, description, attentionRank | null] */
const TOPICS = {
  'climate-action': ['Climate Action & Campaign', '🌍', '#E8492B', 'Campaigns, COP coverage and mobilization calls.', 1],
  'fundraising-mobilizing': ['Fundraising & Mobilizing', '💖', '#F97316', 'Donation drives, matched giving and year-end pushes.', 2],
  'impact-restoration': ['Impact & Restoration', '🌳', '#14B8A6', 'Field results, tree counts and before/after stories.', 3],
  'awareness-days': ['Awareness Days & Events', '📅', '#EAB308', 'International days, solstices and cultural dates.', 4],
  'crews-community': ['Crews & Community', '👥', '#22C55E', 'Youth crews, spotlights and micro-actions.', null],
  'trainings-webinars': ['Trainings & Webinars', '🎓', '#3B82F6', 'Masterclasses, FAQs and application windows.', null],
  'partners-collabs': ['Partners & Collabs', '🤝', '#F59E0B', 'Organizations, joint projects and pavilions.', null],
  'indigenous-justice': ['Indigenous Justice & Culture', '🪖', '#A855F7', 'Voices, territory and cultural celebration.', null],
  'water-oceans': ['Water & Oceans', '💧', '#06B6D4', 'Blue Planet Voices and watershed stories.', null],
  'leaders-bts': ['Leaders & Behind the Scenes', '⭐', '#EC4899', 'Leadership messages and team diaries.', null],
}

/** Old pillar key → new topic key */
const PILLAR_TO_TOPIC = {
  acao: 'climate-action',
  indigena: 'indigenous-justice',
  crews: 'crews-community',
  treinos: 'trainings-webinars',
  parceiros: 'partners-collabs',
  impacto: 'impact-restoration',
  agua: 'water-oceans',
  lideres: 'leaders-bts',
  dias: 'awareness-days',
  doacao: 'fundraising-mobilizing',
}

/** Calendar day → English working title. */
const TITLES = {
  1: 'Giving Tuesday — matched donation',
  2: 'COP31: what came out of the negotiations',
  3: 'Crew of the month: how to start from zero',
  4: 'Masterclass #6 — registration is open',
  5: 'World Soil Day',
  6: 'Behind the scenes: the field team',
  7: 'Togo in numbers: 21,000 trees',
  8: 'Indigenous Voices: IYI alumni',
  9: 'Blue Planet Voices — new episode',
  10: 'Human Rights Day',
  11: '5 ways to prepare for a training',
  12: 'Saturday micro-action',
  13: 'Sunday reflection: why we keep going',
  14: 'Green Jobs Pavilion: careers in food & climate',
  15: 'Mid-month challenge',
  16: 'Before & after: Tagba, Togo',
  17: 'FAQ: trainings and 2027 applications',
  18: 'International Migrants Day',
  19: 'Final week: year-end goal',
  20: 'Blue Planet Voices — featured episode',
  21: 'Solstice: cycles and new beginnings',
  22: 'Crew spotlight: quick questions',
  23: "The ED's end-of-year message",
  24: 'Culture, celebration and territory',
  25: 'Gratitude: 3 wins of 2026',
  26: 'Action kit for 2027',
  27: 'Reflection: what you learned in 2026',
  28: '2026 impact report in numbers',
  29: 'Heading to COP32: our focus for 2027',
  30: 'Partners who made 2026 happen',
  31: '2026 before & after + collective resolution',
}

const FORMATS = ['Carousel', 'Photo', 'Reel', 'Story', 'Video']
const q = (v) => `'${String(v ?? '').replace(/'/g, "''")}'`
const iso = (d) => `${YEAR}-${String(MONTH).padStart(2, '0')}-${String(d).padStart(2, '0')}`

const plan = JSON.parse(readFileSync(SOURCE, 'utf8'))
if (!Array.isArray(plan.posts)) throw new Error('Source plan has no posts[]')

const topicEntries = Object.entries(TOPICS)
const posts = [...plan.posts].sort((a, b) => a.d - b.d)

for (const p of posts) {
  if (!PILLAR_TO_TOPIC[p.pillar]) throw new Error(`Unknown pillar: ${p.pillar}`)
  if (!TOPICS[PILLAR_TO_TOPIC[p.pillar]]) throw new Error(`Unknown topic for pillar: ${p.pillar}`)
  if (!TITLES[Number(p.d)]) throw new Error(`Missing English title for day ${p.d}`)
}

const out = []
const push = (...l) => out.push(...l)

push('-- ============================================================================')
push('-- Seed · Earth Guardians editorial calendar — December 2026')
push(`-- Generated by scripts/make-seed.mjs from ${SOURCE}`)
push('-- Idempotent: re-running resets December 2026 and upserts the same topics.')
push('-- ============================================================================')
push('')
push('begin;')
push('')
push('-- Reset December 2026 so re-seeding is deterministic.')
push(`delete from public.calendar_posts where year = ${YEAR} and month = ${MONTH};`)
push('')
push('-- ------------------------------------------------------------- topics ---')
push('insert into public.calendar_topics')
push('  (key, label, description, color, emoji, sort, needs_attention, attention_rank, updated_at)')
push('values')
topicEntries.forEach(([key, [label, emoji, color, description, rank]], i) => {
  const needs = rank !== null
  push(
    `  (${q(key)}, ${q(label)}, ${q(description)}, ${q(color)}, ${q(emoji)}, ${i + 1}, ${needs}, ${rank}, now())` +
      (i === topicEntries.length - 1 ? '' : ','),
  )
})
push('on conflict (key) do update set')
push('  label = excluded.label,')
push('  description = excluded.description,')
push('  color = excluded.color,')
push('  emoji = excluded.emoji,')
push('  sort = excluded.sort,')
push('  needs_attention = excluded.needs_attention,')
push('  attention_rank = excluded.attention_rank,')
push('  updated_at = now();')
push('')
push('delete from public.calendar_topics where key not in (')
push(`  ${topicEntries.map(([k]) => q(k)).join(', ')}`)
push(') and not exists (select 1 from public.calendar_posts p where p.topic_key = calendar_topics.key);')
push('')
push('-- -------------------------------------------------------------- posts ---')
push(`insert into public.calendar_posts`)
push(`  (day, topic_key, format, title, caption, hashtags, status, sort_order, updated_at)`)
push('values')
posts.forEach((p, i) => {
  const day = Number(p.d)
  const topic = PILLAR_TO_TOPIC[p.pillar]
  const format = FORMATS.includes(p.format) ? p.format : 'Carousel'
  const caption = String(p.caption || '').replace(/\s+/g, ' ').trim()
  const hashtags = [...caption.matchAll(/#[A-Za-z0-9_]+/g)].map((m) => m[0]).join(' ')
  push(
    `  (${q(iso(day))}, ${q(topic)}, ${q(format)}, ${q(TITLES[day])}, ${q(caption)}, ${q(hashtags)}, 'planned', 0, now())` +
      (i === posts.length - 1 ? '' : ','),
  )
})
push(';')
push('')
push('-- ------------------------------------------------------------ settings ---')
push('insert into public.calendar_settings (key, value, updated_at) values')
push(`  ('default_year', to_jsonb(${YEAR}::int), now()),`)
push(`  ('default_month', to_jsonb(${MONTH}::int), now()),`)
push(`  ('week_start', '"sunday"'::jsonb, now()),`)
push(`  ('attention_note', ${q('Topics that need coverage this cycle — reorder with the arrows.')}::jsonb, now())`)
push('on conflict (key) do update set value = excluded.value, updated_at = now();')
push('')
push('commit;')

const outDir = join(ROOT, 'supabase', 'migrations')
mkdirSync(outDir, { recursive: true })
const outFile = join(outDir, '20261120000002_seed_calendar_2026_12.sql')
writeFileSync(outFile, out.join('\n') + '\n', 'utf8')

console.log(`wrote ${outFile}`)
console.log(`  topics: ${topicEntries.length}`)
console.log(`  posts : ${posts.length} (${YEAR}-${String(MONTH).padStart(2, '0')})`)
